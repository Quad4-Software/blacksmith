// Generates web_src/css/tailwind-theme.css: the Tailwind 3 theme from the old tailwind.config.ts
// expressed as a Tailwind 4 @theme block. Colors come from the :root --color-* custom properties
// declared in the two theme files, mapped to var(--color-xxx). Run: node tools/generate-tailwind-theme.ts
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function extractColorVars(css: string): Set<string> {
  const vars = new Set<string>();
  for (const selMatch of css.matchAll(/:root\s*\{/g)) {
    // walk to the matching closing brace, honoring nesting
    let depth = 1, i = selMatch.index + selMatch[0].length;
    while (i < css.length && depth > 0) {
      if (css[i] === '{') depth++;
      else if (css[i] === '}') depth--;
      i++;
    }
    for (const dm of css.slice(selMatch.index, i - 1).matchAll(/--color-[\w-]+\s*:/g)) {
      vars.add(dm[0].slice(8, -1).trim());
    }
  }
  return vars;
}

export function generate(): string {
  const vars = new Set<string>();
  for (const theme of ['theme-gitea-light.css', 'theme-gitea-dark.css']) {
    const css = readFileSync(`${root}/web_src/css/themes/${theme}`, 'utf8');
    for (const v of extractColorVars(css)) vars.add(v);
  }

  const lines = [];
  lines.push('/* generated by tools/generate-tailwind-theme.ts, do not edit */', '@theme {', '  --color-*: initial;');
  for (const v of Array.from(vars).sort()) {
    lines.push(`  --color-${v}: var(--color-${v});`);
  }
  lines.push('  --color-inherit: inherit;', '  --color-current: currentcolor;', '  --color-transparent: transparent;', '', '  --radius-none: 0;', '  --radius-sm: 2px;', '  --radius: var(--border-radius);', '  --radius-md: var(--border-radius-medium);', '  --radius-lg: 8px;', '  --radius-xl: 12px;', '  --radius-2xl: 16px;', '  --radius-3xl: 24px;', '  --radius-full: var(--border-radius-full);', '', '  --font-sans: var(--fonts-regular);', '  --font-mono: var(--fonts-monospace);', '', '  --font-weight-light: var(--font-weight-light);', '  --font-weight-normal: var(--font-weight-normal);', '  --font-weight-medium: var(--font-weight-medium);', '  --font-weight-semibold: var(--font-weight-semibold);', '  --font-weight-bold: var(--font-weight-bold);', '');
  const sizes = {
    xs: '12px', sm: '14px', base: '16px', lg: '18px', xl: '20px',
    '2xl': '24px', '3xl': '30px', '4xl': '36px', '5xl': '48px', '6xl': '60px',
    '7xl': '72px', '8xl': '96px', '9xl': '128px',
  };
  lines.push(
    ...Object.entries(sizes).map(([k, v]) => `  --text-${k}: ${v};`),
    ...Array.from({length: 100}, (_, i) => `  --text-${i}: ${i === 0 ? '0' : `${i}px`};`),
    '}', '',
    // utilities that were added by the tailwind.config.ts plugins
    // hidden must beat every other display utility: the doubled class keeps specificity 0,2,0
    '.tw\\:hidden.tw\\:hidden {', '  display: none !important;', '}', '',
    '@utility transform-reset {', '  --tw-translate-x: 0;', '  --tw-translate-y: 0;', '  --tw-rotate: 0;', '  --tw-skew-x: 0;', '  --tw-skew-y: 0;', '  --tw-scale-x: 1;', '  --tw-scale-y: 1;', '}', '',
    '@utility break-anywhere {', '  overflow-wrap: anywhere;', '}', '',
  );
  return lines.join('\n');
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(`${root}/web_src/css/tailwind-theme.css`, generate());
  console.info('wrote web_src/css/tailwind-theme.css');
}
